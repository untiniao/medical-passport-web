export function getStrings(lang) {
  return strings[lang] || strings.en
}

export function translateCondition(lang, key) {
  const dict = getStrings(lang).conditions || {}
  return dict[key] || key
}

export function translateBlood(lang, value) {
  if (!value || !String(value).trim()) return getStrings(lang).unknown
  const v = String(value).trim()
  const unknownTokens = ['不清楚', 'unknown', 'unsure', '不明', '不知', '모름', 'desconocido', 'desconhecido']
  if (unknownTokens.includes(v.toLowerCase()) || unknownTokens.includes(v)) {
    return getStrings(lang).unknown
  }
  return v
}

export function formatList(value) {
  if (!value) return []
  if (Array.isArray(value)) return value.map((x) => String(x).trim()).filter(Boolean)
  return String(value)
    .split(/[,;|]/)
    .map((x) => x.trim())
    .filter(Boolean)
}

export function formatTimestamp(value, lang) {
  if (!value) return ''
  const date = value.toDate ? value.toDate() : new Date(value)
  if (Number.isNaN(date.getTime())) return ''
  const locale =
    lang === 'zh-TW' ? 'zh-Hant' : lang === 'zh-CN' ? 'zh-Hans' : lang
  return new Intl.DateTimeFormat(locale, {
    dateStyle: 'medium',
    timeStyle: 'short',
  }).format(date)
}
